// Command const generates Go (and optionally Swift) constants with helper
// functions from a simple text list. See README.md for the input format.
//
//	go install github.com/monopolly/const@latest
//	const status.const   # writes status.go (and status.swift with #swift)
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"strings"
)

// fields — значения списка в порядке файла
var fields []*field

func main() {
	log.SetFlags(0)

	if len(os.Args) != 2 {
		log.Fatalf("usage: %s <file>\nexample: %s status.const   (writes status.go)", filepath.Base(os.Args[0]), filepath.Base(os.Args[0]))
	}

	input := os.Args[1]
	base := strings.TrimSuffix(input, filepath.Ext(input))

	// не перезаписываем исходный файл результатом (status.go > status.go)
	for _, ext := range []string{".go", ".swift"} {
		if base+ext == input {
			log.Fatalf("input file %s would be overwritten by output, use another extension (e.g. %s.const)", input, base)
		}
	}

	b, err := os.ReadFile(input)
	if err != nil {
		log.Fatal(err)
	}

	goCode, swiftCode := generate(string(b))

	if err := os.WriteFile(base+".go", goCode, 0o644); err != nil {
		log.Fatal(err)
	}
	if swiftCode != nil {
		if err := os.WriteFile(base+".swift", swiftCode, 0o644); err != nil {
			log.Fatal(err)
		}
	}
}

// reset очищает состояние генератора (нужно для нескольких запусков в тестах)
func reset() {
	fields = nil
	settings = Settings{}
	helps = Help{}
	declared = map[string]string{}
}

// generate возвращает go код и swift код (nil, если нет #swift)
func generate(in string) (goCode, swiftCode []byte) {
	reset()

	settings.parse(in)

	// go (до help: help перечисляет сгенерированные функции)
	body := generateGo()

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by github.com/monopolly/const. DO NOT EDIT.\n\npackage %s\n", settings.Package)
	buf.Write(helps.render())
	buf.Write(body)

	// gofmt: заодно проверяет, что сгенерирован синтаксически корректный код
	goCode, err := format.Source(buf.Bytes())
	if err != nil {
		log.Printf("generated go code is invalid: %v", err)
		goCode = buf.Bytes()
	}

	if settings.Swift {
		swiftCode = generateSwift()
	}
	return
}
